/// Return the glyph bitmap for a character (or space for out-of-range).
pub fn font_get(c: char) -> &'static [u8; FONT_H as usize] {
    let idx = (c as usize).wrapping_sub(32);
    if idx < GLYPHS.len() {
        &GLYPHS[idx]
    } else {
        &GLYPHS[0]
    }
}

